#!/usr/bin/env swift
// Generates Sources/SFSymbols/SFSymbols+PrivateSystemSymbolName.swift: one constant for every name in the private
// system symbol set (CoreGlyphsPrivate.bundle) of the running macOS.
//
// Ordering, naming and availability follow SFSymbolsGenerator, which generates SFSymbols+SystemSymbolName.swift from
// the SF Symbols app: names sorted by release and then by name, dot-separated components joined in camel case, an
// underscore before a leading digit, and the operating system versions of the release as the availability. Unlike
// SFSymbolsGenerator, every Swift keyword gets backticks, not only `return`, `case` and `repeat`.
//
// Usage: swift Scripts/GeneratePrivateSystemSymbolNames.swift

import Foundation

let availabilityListURL = URL(fileURLWithPath: "/System/Library/CoreServices/CoreGlyphsPrivate.bundle/Contents/Resources/name_availability.plist")

let outputURL = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent()
    .deletingLastPathComponent()
    .appendingPathComponent("Sources/SFSymbols/SFSymbols+PrivateSystemSymbolName.swift")

/// Words that need backticks to be the name of a declaration.
let keywords: Set<String> = [
    // Keywords used in declarations
    "associatedtype", "borrowing", "class", "consuming", "deinit", "enum", "extension", "fileprivate", "func", "import",
    "init", "inout", "internal", "let", "nonisolated", "open", "operator", "private", "precedencegroup", "protocol",
    "public", "rethrows", "static", "struct", "subscript", "typealias", "var",
    // Keywords used in statements
    "break", "case", "catch", "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in",
    "repeat", "return", "throw", "switch", "where", "while",
    // Keywords used in expressions and types
    "Any", "as", "await", "false", "is", "nil", "self", "Self", "super", "throws", "true", "try",
    // Keywords reserved in particular contexts that clash with a member name
    "Protocol", "Type",
]

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("error: \(message)\n".utf8))
    exit(1)
}

func constantName(forSymbolName symbolName: String) -> String {
    let components = symbolName.components(separatedBy: ".")
    let camelCaseName = components[0] + components.dropFirst().map { component in
        component.prefix(1).uppercased() + component.dropFirst()
    }.joined()
    return camelCaseName.first?.isNumber == true ? "_" + camelCaseName : camelCaseName
}

func availabilityAttribute(forOperatingSystemVersions operatingSystemVersions: [String: String]) -> String {
    let platforms = operatingSystemVersions.map { operatingSystemName, operatingSystemVersion in
        "\(operatingSystemName) \(operatingSystemVersion)"
    }
    return "@available(" + platforms.sorted().joined(separator: ", ") + ", *)"
}

guard
    let availabilityListData = try? Data(contentsOf: availabilityListURL),
    let availabilityList = try? PropertyListSerialization.propertyList(from: availabilityListData, format: nil) as? [String: Any],
    let releaseBySymbolName = availabilityList["symbols"] as? [String: String],
    let operatingSystemVersionsByRelease = availabilityList["year_to_release"] as? [String: [String: String]]
else {
    fail("Cannot read the symbols and their releases from \(availabilityListURL.path)")
}

let releasesWithoutVersions = Set(releaseBySymbolName.values).subtracting(operatingSystemVersionsByRelease.keys)
guard releasesWithoutVersions.isEmpty else {
    fail("These releases have no operating system versions: \(releasesWithoutVersions.sorted())")
}

let invalidSymbolNames = releaseBySymbolName.keys.filter { symbolName in
    constantName(forSymbolName: symbolName).wholeMatch(of: #/[A-Za-z_][A-Za-z0-9_]*/#) == nil
}
guard invalidSymbolNames.isEmpty else {
    fail("These names do not make valid Swift identifiers: \(invalidSymbolNames.sorted())")
}

let symbolNamesByConstantName = Dictionary(grouping: releaseBySymbolName.keys, by: constantName(forSymbolName:))
let collidingSymbolNames = symbolNamesByConstantName.values.filter { symbolNames in symbolNames.count > 1 }
guard collidingSymbolNames.isEmpty else {
    fail("These names make the same Swift identifier: \(collidingSymbolNames.map { symbolNames in symbolNames.sorted() })")
}

let sortedSymbols = releaseBySymbolName.sorted { leftSymbol, rightSymbol in
    leftSymbol.value == rightSymbol.value ? leftSymbol.key < rightSymbol.key : leftSymbol.value < rightSymbol.value
}

var lines = [
    "// This file is generated by Scripts/GeneratePrivateSystemSymbolNames.swift. Do not edit it by hand.",
    "// Source: CoreGlyphsPrivate.bundle of macOS \(ProcessInfo.processInfo.operatingSystemVersionString).",
    "",
    "#if SFSYMBOLS_PRIVATE",
    "",
    "extension SFSymbols.PrivateSystemSymbolName {",
    "",
]

for (symbolName, release) in sortedSymbols {
    let declaredName = constantName(forSymbolName: symbolName)
    let escapedName = keywords.contains(declaredName) ? "`\(declaredName)`" : declaredName
    lines += [
        "    /// SF Symbols's name：\(symbolName)",
        "    " + availabilityAttribute(forOperatingSystemVersions: operatingSystemVersionsByRelease[release]!),
        "    public static let \(escapedName) = Self(rawValue: \"\(symbolName)\")",
        "",
    ]
}

lines += [
    "}",
    "",
    "#endif",
    "",
]

do {
    try lines.joined(separator: "\n").write(to: outputURL, atomically: true, encoding: .utf8)
} catch {
    fail("Cannot write \(outputURL.path): \(error)")
}

print("Wrote \(sortedSymbols.count) private symbol names to \(outputURL.path)")
