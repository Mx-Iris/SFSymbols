import Foundation

/// The names in a `name_availability.plist` of SF Symbols, ordered and named the way the generated constants are.
///
/// The rules follow SFSymbolsGenerator, which generated the public constants before this plugin existed: names sorted
/// by release and then by name, dot-separated components joined in camel case, an underscore before a leading digit,
/// and the operating system versions of the release as the availability. Unlike SFSymbolsGenerator, every Swift keyword
/// gets backticks, not only `return`, `case` and `repeat`.
struct SymbolNameList {
    struct Entry {
        let symbolName: String
        let constantName: String
        let availabilityAttribute: String
    }

    let entries: [Entry]

    init(contentsOf availabilityListURL: URL) throws {
        let availabilityListData: Data
        do {
            availabilityListData = try Data(contentsOf: availabilityListURL)
        } catch {
            throw GenerationError("Cannot read \(availabilityListURL.path): \(error.localizedDescription)")
        }

        guard
            let availabilityList = try? PropertyListSerialization.propertyList(from: availabilityListData, format: nil) as? [String: Any],
            let releaseBySymbolName = availabilityList["symbols"] as? [String: String],
            let operatingSystemVersionsByRelease = availabilityList["year_to_release"] as? [String: [String: String]]
        else {
            throw GenerationError("\(availabilityListURL.path) has no symbols with releases")
        }

        let releasesWithoutVersions = Set(releaseBySymbolName.values).subtracting(operatingSystemVersionsByRelease.keys)
        guard releasesWithoutVersions.isEmpty else {
            throw GenerationError("These releases in \(availabilityListURL.path) have no operating system versions: \(releasesWithoutVersions.sorted())")
        }

        let invalidSymbolNames = releaseBySymbolName.keys.filter { symbolName in
            Self.constantName(forSymbolName: symbolName).wholeMatch(of: #/[A-Za-z_][A-Za-z0-9_]*/#) == nil
        }
        guard invalidSymbolNames.isEmpty else {
            throw GenerationError("These names in \(availabilityListURL.path) do not make valid Swift identifiers: \(invalidSymbolNames.sorted())")
        }

        let symbolNamesByConstantName = Dictionary(grouping: releaseBySymbolName.keys, by: Self.constantName(forSymbolName:))
        let collidingSymbolNames = symbolNamesByConstantName.values.filter { symbolNames in symbolNames.count > 1 }
        guard collidingSymbolNames.isEmpty else {
            throw GenerationError("These names in \(availabilityListURL.path) make the same Swift identifier: \(collidingSymbolNames.map { symbolNames in symbolNames.sorted() })")
        }

        entries = releaseBySymbolName
            .sorted { leftSymbol, rightSymbol in
                leftSymbol.value == rightSymbol.value ? leftSymbol.key < rightSymbol.key : leftSymbol.value < rightSymbol.value
            }
            .map { symbolName, release in
                Entry(
                    symbolName: symbolName,
                    constantName: Self.constantName(forSymbolName: symbolName),
                    availabilityAttribute: Self.availabilityAttribute(forOperatingSystemVersions: operatingSystemVersionsByRelease[release]!)
                )
            }
    }

    func swiftSource(extending typeName: String, generatedFrom sourceDescription: String, compilationCondition: String?) -> String {
        var lines = [
            "// This file is generated by the GenerateSymbolNames package plugin. Do not edit it by hand.",
            "// Source: \(sourceDescription)",
            "",
        ]
        if let compilationCondition {
            lines += ["#if \(compilationCondition)", ""]
        }
        lines += ["extension \(typeName) {", ""]
        for entry in entries {
            let declaredName = Self.keywords.contains(entry.constantName) ? "`\(entry.constantName)`" : entry.constantName
            lines += [
                "    /// SF Symbols's name：\(entry.symbolName)",
                "    \(entry.availabilityAttribute)",
                "    public static let \(declaredName) = Self(rawValue: \"\(entry.symbolName)\")",
                "",
            ]
        }
        lines += ["}", ""]
        if compilationCondition != nil {
            lines += ["#endif", ""]
        }
        return lines.joined(separator: "\n")
    }

    /// The raw values of the constants in a file this plugin generated; none when the file does not exist yet.
    static func symbolNames(inGeneratedSourceAt sourceURL: URL) -> Set<String> {
        guard let source = try? String(contentsOf: sourceURL, encoding: .utf8) else {
            return []
        }
        let rawValueFragments = source.components(separatedBy: "Self(rawValue: \"").dropFirst()
        return Set(rawValueFragments.compactMap { rawValueFragment in
            rawValueFragment.components(separatedBy: "\")").first
        })
    }

    /// Words that need backticks to be the name of a declaration.
    private static let keywords: Set<String> = [
        // Keywords used in declarations
        "associatedtype", "borrowing", "class", "consuming", "deinit", "enum", "extension", "fileprivate", "func", "import",
        "init", "inout", "internal", "let", "nonisolated", "open", "operator", "private", "precedencegroup", "protocol",
        "public", "rethrows", "static", "struct", "subscript", "typealias", "var",
        // Keywords used in statements
        "break", "case", "catch", "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in",
        "repeat", "return", "throw", "switch", "where", "while",
        // Keywords used in expressions and types
        "Any", "as", "await", "false", "is", "nil", "self", "Self", "super", "throws", "true", "try",
        // Keywords reserved in particular contexts that clash with a member name
        "Protocol", "Type",
    ]

    private static func constantName(forSymbolName symbolName: String) -> String {
        let components = symbolName.components(separatedBy: ".")
        let camelCaseName = components[0] + components.dropFirst().map { component in
            component.prefix(1).uppercased() + component.dropFirst()
        }.joined()
        return camelCaseName.first?.isNumber == true ? "_" + camelCaseName : camelCaseName
    }

    private static func availabilityAttribute(forOperatingSystemVersions operatingSystemVersions: [String: String]) -> String {
        let platforms = operatingSystemVersions.map { operatingSystemName, operatingSystemVersion in
            "\(operatingSystemName) \(operatingSystemVersion)"
        }
        return "@available(" + platforms.sorted().joined(separator: ", ") + ", *)"
    }
}
